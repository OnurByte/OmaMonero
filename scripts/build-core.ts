import {build} from 'esbuild';
import {mkdirSync,readFileSync,writeFileSync} from 'node:fs';
const version=JSON.parse(readFileSync('manifest.json','utf8')).version;
const generated=`qml/v${version.replaceAll('.','_')}/generated`;
const result=await build({entryPoints:['src/core/index.ts'],bundle:true,format:'iife',globalName:'OmaCore',target:'es2016',platform:'neutral',mainFields:['module','main'],write:false,legalComments:'inline',minify:true,supported:{bigint:false}});
mkdirSync(generated,{recursive:true});
writeFileSync(generated+'/Core.js','.pragma library\n// Generated by npm run build. Sources: src/core. Includes js-sha3 and qrcode-generator; see THIRD_PARTY_NOTICES.md.\n'+result.outputFiles[0].text+'\nfunction api() { return OmaCore; }\n');
