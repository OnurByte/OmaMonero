import {build} from 'esbuild';
import {mkdirSync,readFileSync,writeFileSync} from 'node:fs';
import {dirname} from 'node:path';
const version=JSON.parse(readFileSync('manifest.json','utf8')).version;
const generated=`qml/v${version.replaceAll('.','_')}/generated`;
// Downlevel dependency built-ins without modifying global host prototypes.
const qmlBuiltins={name:'qml-builtins',setup(builder){
  builder.onLoad({filter:/[/\\]smol-toml[/\\].*\.js$/},args=>({
    contents:readFileSync(args.path,'utf8').replace(/\.replaceAll\((['"])_\1,\s*(['"])\2\)/g,".replace(/_/g, '')"),
    loader:'js',resolveDir:dirname(args.path)
  }));
}};
const result=await build({entryPoints:['src/core/index.ts'],bundle:true,format:'iife',globalName:'OmaCore',target:'es2016',platform:'neutral',mainFields:['module','main'],write:false,legalComments:'inline',supported:{bigint:false},define:{'Object.hasOwn':'Object.prototype.hasOwnProperty.call'},plugins:[qmlBuiltins]});
mkdirSync(generated,{recursive:true});
writeFileSync(generated+'/Core.js','.pragma library\n// Generated by npm run build. Sources: src/core. Includes js-sha3, qrcode-generator and smol-toml; see THIRD_PARTY_NOTICES.md.\n'+result.outputFiles[0].text+'\nfunction api() { return OmaCore; }\n');
